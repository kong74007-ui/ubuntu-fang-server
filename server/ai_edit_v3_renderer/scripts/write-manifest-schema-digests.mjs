import {createHash} from "node:crypto";
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const SCHEMAS = Object.freeze({
  "1.0": new URL("../../content_domains/ai_edit_v3/schemas/render-manifest-v1.schema.json", import.meta.url),
  "2.0": new URL("../../content_domains/ai_edit_v3/schemas/render-manifest-v2.schema.json", import.meta.url),
});
const DEFAULT_OUTPUT = fileURLToPath(new URL("../src/manifest-schema-digests.mjs", import.meta.url));

async function generatedBytes() {
  const entries = await Promise.all(Object.entries(SCHEMAS).map(async ([version, location]) => [
    version,
    createHash("sha256").update(await readFile(location)).digest("hex"),
  ]));
  const lines = entries.map(([version, digest]) => `  ${JSON.stringify(version)}: ${JSON.stringify(digest)},`).join("\n");
  return Buffer.from(`// Generated by scripts/write-manifest-schema-digests.mjs from authoritative schemas.\nexport const MANIFEST_SCHEMA_SHA256_BY_VERSION = Object.freeze({\n${lines}\n});\n`, "utf8");
}

export async function writeManifestSchemaDigests(destination = DEFAULT_OUTPUT) {
  await writeFile(path.resolve(destination), await generatedBytes());
}

export async function checkManifestSchemaDigests(destination = DEFAULT_OUTPUT) {
  const [actual, expected] = await Promise.all([readFile(path.resolve(destination)), generatedBytes()]);
  if (!actual.equals(expected)) throw new Error("manifest_schema_digests_stale");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args[0] === "--check";
  const outputIndex = args.indexOf("--output");
  if ((args[0] && !check && args[0] !== "--output") || (outputIndex >= 0 && !args[outputIndex + 1]) || args.some((value, index) => value === "--output" ? false : index > 0 && index !== outputIndex + 1)) {
    throw new Error("manifest_schema_digests_arguments_invalid");
  }
  const output = outputIndex >= 0 ? args[outputIndex + 1] : DEFAULT_OUTPUT;
  if (check) await checkManifestSchemaDigests(output);
  else await writeManifestSchemaDigests(output);
}
